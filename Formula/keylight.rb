class Keylight < Formula
  desc "Manage Keylight apps, licenses, and integrations from the terminal"
  homepage "https://keylight.dev"
  license "Apache-2.0"

  livecheck do
    url :stable
    strategy :github_latest
  end

  bottle do
    root_url "https://github.com/keylight-dev/homebrew-tap/releases/download/keylight-0.2.4"
    sha256 cellar: :any_skip_relocation, arm64_tahoe:  "f5aa71f63496e18ef41554c9da83e1429c42b64a7421f69a71db0128062d4a5c"
    sha256 cellar: :any_skip_relocation, sequoia:      "8ce5c558ad9148edb01b2b7cd87af374ca850f7506f7e0ae085de29ab758d3b9"
    sha256 cellar: :any_skip_relocation, x86_64_linux: "d796150679e8ea1b835d9c2dc3e0a7b3c2c31769a7190e1f3b5b3b839ad1b781"
  end

  # Prebuilt binaries where they are published, source builds everywhere else.
  # The crate is `keylight-cli`; the binary it installs is `keylight`.
  on_macos do
    on_arm do
      url "https://github.com/keylight-dev/keylight-cli/releases/download/v0.2.4/keylight-aarch64-apple-darwin"
      sha256 "bf383e722aac16a84b5d826ef1623c5f0e6bbd1efd8e7ea5941826f67a95e5dc"
    end

    on_intel do
      url "https://github.com/keylight-dev/keylight-cli/releases/download/v0.2.4/keylight-x86_64-apple-darwin"
      sha256 "c7d8e11f2dc33179ea7ff0f8aad8086b395b01a2e6cfc976ec5656b26d16b765"
    end
  end

  on_linux do
    on_intel do
      url "https://github.com/keylight-dev/keylight-cli/releases/download/v0.2.4/keylight-x86_64-unknown-linux-gnu"
      sha256 "e50850de6ee7417216bdb5acd4bbf38326ddff20ed14173b530a102f845fdd7e"
    end

    on_arm do
      url "https://static.crates.io/crates/keylight-cli/keylight-cli-0.2.4.crate"
      sha256 "df4b33e64511ddda0ae0d840f09b9c5757b9d5386516c257ea278eaa71954dcc"
      depends_on "rust" => :build
    end
  end

  # Bottles are built by the tap's CI on pull requests and published by
  # `brew pr-pull`. They matter more than usual here: without one, brew takes the
  # build-from-source path, which enforces a minimum Xcode for the running macOS
  # and hard-fails when the installed Xcode is older — an error about Xcode, on a
  # machine that only wanted a licensing CLI.

  def install
    # The source archive has a Cargo.toml; a downloaded release binary does not.
    if File.exist?("Cargo.toml")
      system "cargo", "install", *std_cargo_args
    else
      # A bare binary arrives 0644 from the release asset, so set the mode
      # rather than assuming an archive preserved it.
      bin.install Dir["keylight-*"].first => "keylight"
      chmod 0755, bin/"keylight"
    end

    # Shell completions and a man page, generated by the binary itself.
    generate_completions_from_executable(bin/"keylight", "completions")
    (man1/"keylight.1").write Utils.safe_popen_read(bin/"keylight", "man")
  end

  test do
    assert_match "keylight #{version}", shell_output("#{bin}/keylight --version")
    assert_match "Usage: keylight", shell_output("#{bin}/keylight --help")

    # No command may block on a prompt — that is the property the whole CLI
    # rests on. Unauthenticated, it must exit 2 rather than ask for anything.
    output = shell_output("#{bin}/keylight auth status 2>&1", 2)
    assert_match "no API token configured", output
  end
end
